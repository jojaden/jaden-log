/** 페이지 주소로 언어를 정한다 — 컴포넌트는 Astro.url 을 넘겨 쓴다 */
export const langOf = (url: URL): Lang => (/^\/en(\/|$)/.test(url.pathname) ? 'en' : 'ko');

/** 한국어 기준 경로(/category, /1 …)를 그 언어의 경로로 */
export const localize = (path: string, lang: Lang) => (lang === 'en' ? (path === '/' ? '/en' : `/en${path}`) : path);

/** [...lang] 라우트의 params 값 — 한국어는 비워서 루트에 */
